import { cp, readFile, rm, writeFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'

// 1. Generate src/chrome.generated.ts from the Brand System release mirrored in ./brand. The header and
//    footer content is never typed by hand: change it in the Brand System, then run npm run brand:sync.
const read = async (path) => JSON.parse(await readFile(new URL(`../${path}`, import.meta.url), 'utf8'))
const [chrome, lock, packageJson] = await Promise.all([
  read('brand/site-chrome/navigation.json'),
  read('brand.lock.json'),
  read('package.json'),
])
const { $comment, ...content } = chrome
await writeFile(
  new URL('../src/chrome.generated.ts', import.meta.url),
  `// Generated by scripts/build.mjs from brand/site-chrome/navigation.json (Brand System ${lock.tag}). Do not edit.\n` +
    `export const chrome = ${JSON.stringify(content, null, 2)} as const\n\n` +
    `/** The Brand System release the header and footer come from. */\n` +
    `export const brandVersion = ${JSON.stringify(lock.version)}\n\n` +
    `/** This package's version, stamped on the header and footer as data-proxima-shell-version. */\n` +
    `export const shellVersion = ${JSON.stringify(packageJson.version)}\n`,
)

// 2. Compile and copy the stylesheet.
await rm(new URL('../dist', import.meta.url), { recursive: true, force: true })
const typeScript = spawnSync(
  process.execPath,
  ['node_modules/typescript/bin/tsc', '-p', 'tsconfig.build.json'],
  { cwd: new URL('..', import.meta.url), stdio: 'inherit' },
)
if (typeScript.status !== 0) process.exit(typeScript.status ?? 1)

await cp(new URL('../src/styles.css', import.meta.url), new URL('../dist/styles.css', import.meta.url))
